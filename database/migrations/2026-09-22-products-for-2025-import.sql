-- มาจากรายงาน database/2025-รายงานตรวจสอบ.xlsx ชีต "2 สินค้าไม่มีในระบบ" (5 ชนิด)
-- เจ้านายเคาะ 2026-09-22:
--   ✅ เพิ่ม 3 ตัว (ในไฟล์นี้)
--   ↩︎ อีก 2 ตัว "มีอยู่แล้ว" แค่สะกดต่างกัน → ไม่เพิ่ม แต่ต้องแมพชื่อตอน transform:
--        'เเถมฟรี เเก้วกาแฟเซรามิค'  →  'แถมฟรี แก้วกาแฟเซรามิค'  (id 139) · ต่างแค่ เเ กับ แ
--        'รอส่งปฏิทินโฮปฟูล'         →  'แถมฟรี ปฏิทิน Hopeful'   (id 105) · เจ้านายยืนยันว่าตัวเดียวกัน
--
-- 🔴 กับดักตัวสะกด: ในระบบมีสินค้า 9 รายการที่สะกดด้วย 'เเ' (สระเอ 2 ตัว) แทน 'แ' ตัวเดียว
--    เช่น 'Beta Herb (10 เเคปซูล)' · 'Madame Louise Sundrops (กันเเดด)' · 'เเถมฟรี แผ่นทองแชกงหมิว'
--    หน้าตาเหมือนกันแต่คอมพิวเตอร์มองคนละตัว → transform.py ต้องปรับรูป (เเ→แ) ก่อนเทียบชื่อ
--    ไม่งั้นจะสร้างสินค้าซ้ำโดยไม่รู้ตัว
--
-- ℹ️ is_active: ตรวจแล้ว **ไม่มีที่ไหนในระบบใช้คอลัมน์นี้เลย** (ไม่มีฟังก์ชัน DB หรือหน้าเว็บกรอง)
--    ตั้ง false จึงมีผลแค่เป็นบันทึกว่าเลิกขายแล้ว ไม่ได้ซ่อนจากตัวเลือกใดๆ

insert into public.products (category_id, name, is_freebie, is_active)
select c.id, v.name, v.freebie, v.active
from (values
  -- ขายแยกเป็นแผ่น ไม่ใช่ทั้งกล่อง → คนละตัวกับ 'Dr.emiser Mask' (id 36) ที่มีอยู่ · เลิกขายแล้ว
  ('Dr.emiser Mask (แผ่น)',        'EMISER', 'แบรนด์อื่นๆ', false, false),
  -- มีแต่ 'Beta Cal Plus กล่อง (10 แคปซูล)' (id 52) ซึ่งคนละ SKU · เลิกขายแล้ว
  ('Beta Cal Plus ซอง (5 แคปซูล)',  'CAL',    'HOPEFUL',   false, false),
  -- เจ้านายยืนยัน: ไม่ใช่ 'เเถมฟรี แผ่นทองแชกงหมิว' (id 67) คนละตัวกัน
  ('แถมฟรี แผ่นทอง Hopeful',        'แถม',    'HOPEFUL',   true,  true)
) as v(name, cat, brand, freebie, active)
join public.categories c on c.name = v.cat
join public.brands b on b.id = c.brand_id and b.name = v.brand
where not exists (
  -- กันรันซ้ำ และกันชนกับชื่อที่สะกดด้วย เเ
  select 1 from public.products p
  where replace(p.name, 'เเ', 'แ') = replace(v.name, 'เเ', 'แ')
);
